/**
 * The NovaPlay accounts server (the user's sports proxy, which keeps accounts in a private GitHub repository and holds
 * its key). Not a secret: the apps carry no key. local.properties can point elsewhere:
 *   novaplay.accountsServer=https://xtream-sports-proxy-syls.onrender.com
 */
val secretsDir = layout.buildDirectory.dir("generated/secrets/kotlin").get().asFile
run {
    val p = Properties()
    rootProject.file("local.properties").takeIf { it.exists() }?.reader()?.use { p.load(it) }
    // -PnovaplayNoAccounts=true: a test build with accounts off (no login page), for trying screens on an emulator.
    val server = if (project.hasProperty("novaplayNoAccounts")) ""
        else p.getProperty("novaplay.accountsServer", "https://xtream-sports-proxy-syls.onrender.com").trim()
    require(server.isEmpty() || Regex("""https?://[A-Za-z0-9.:/_-]*""").matches(server)) { "novaplay.accountsServer must be a plain http(s) address" }
    val f = File(secretsDir, "io/github/novatv/play/data/AccountsConfig.kt")
    val text = listOf(
        "package io.github.novatv.play.data",
        "",
        "/** Generated by shared/build.gradle.kts. */",
        "internal object AccountsConfig {",
        "    const val SERVER = \"$server\"",
        "}",
        "",
    ).joinToString("\n")
    if (!f.exists() || f.readText() != text) { f.parentFile.mkdirs(); f.writeText(text) }
}

/** iOS builds need Xcode, so the iPhone targets only exist on a Mac (the cloud build). */
val onMac = System.getProperty("os.name").startsWith("Mac")

kotlin {
    androidTarget { compilerOptions { jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17) } }
    jvm("desktop") { compilerOptions { jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17) } }
    if (onMac) listOf(iosArm64(), iosSimulatorArm64()).forEach {
        it.binaries.framework { baseName = "Shared"; isStatic = true }
    }

    sourceSets {
        // Android and Windows both run on the JVM: what they share lives here.
        val jvmShared by creating { dependsOn(commonMain.get()) }
        androidMain.get().dependsOn(jvmShared)
        // Windows and iPhone: mouse and touch versions of the TV widgets.
        val screenMain by creating { dependsOn(commonMain.get()) }
        if (onMac) {
            // The default hierarchy is off (the custom sets above), so iOS is wired by hand.
            val ios = maybeCreate("iosMain")
            ios.dependsOn(screenMain)
            getByName("iosArm64Main").dependsOn(ios)
            getByName("iosSimulatorArm64Main").dependsOn(ios)
            ios.dependencies { implementation("io.ktor:ktor-client-darwin:3.1.3") }
        }
        commonMain.get().kotlin.srcDir(secretsDir)
        commonMain.dependencies {
            implementation(compose.runtime)
            implementation(compose.foundation)
            implementation(compose.ui)
            implementation(compose.materialIconsExtended)
            implementation(compose.components.resources)
            implementation("org.jetbrains.kotlinx:kotlinx-coroutines-core:1.10.2")
            implementation("org.jetbrains.kotlinx:kotlinx-serialization-json:1.8.1")
            implementation("org.jetbrains.kotlinx:kotlinx-datetime:0.6.2")
            implementation("org.jetbrains.kotlinx:atomicfu:0.27.0")
            implementation("com.squareup.okio:okio:3.12.0")
            implementation("io.ktor:ktor-client-core:3.1.3")
            implementation("androidx.sqlite:sqlite:2.5.2")
            implementation("androidx.sqlite:sqlite-bundled:2.5.2")
            implementation("io.coil-kt.coil3:coil-compose:3.2.0")
            implementation("io.coil-kt.coil3:coil-network-ktor3:3.2.0")
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
